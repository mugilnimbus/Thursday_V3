"""What the gateway's logic needs from storage and from the other services, stated as interfaces ("ports").

Each one lists only what its user calls. `infrastructure` holds the classes that fit them (SQLite stores,
HTTP clients), and only `bootstrap` knows which class sits behind which port. They are structural: a class
fits a port by having the methods, without inheriting from it, so a test can pass a small fake.
"""

from collections.abc import AsyncIterator, Mapping
from datetime import timedelta
from typing import Any, Protocol

from thursday_contracts.events import EventEnvelope
from thursday_contracts.metrics import MetricsSample

from thursday_gateway.domain.model import Chat, Outgoing, OutgoingStatus, Project, RecordState

Record = dict[str, Any]
"""One row of stored data as plain values, ready to be sent to a client."""


class Reply(Protocol):
    """Another service's HTTP answer: as much of it as the gateway reads."""

    @property
    def status_code(self) -> int: ...

    @property
    def text(self) -> str: ...

    @property
    def content(self) -> bytes: ...

    @property
    def headers(self) -> Mapping[str, str]: ...

    def json(self) -> Any: ...


# --- the gateway's own records -------------------------------------------------------------------


class ProjectRecords(Protocol):
    """Projects and chats, for the project service."""

    def add_project(self, p: Project) -> None: ...

    def save_project(self, p: Project) -> None: ...

    def project(self, project_id: str) -> Project | None: ...

    def add_chat(self, c: Chat) -> None: ...

    def save_chat(self, c: Chat) -> None: ...

    def chat(self, chat_id: str) -> Chat | None: ...

    def begin_chat_delete(self, chat_id: str) -> None: ...

    def chats(self, project_id: str) -> list[Record]: ...


class RelayRecords(Protocol):
    """The queue of messages on their way to the voice agent, and where each message belongs."""

    def enqueue(
        self, chat_id: str, client_message_id: str, text: str, direct: bool = False
    ) -> tuple[Outgoing, bool]: ...

    def next_queued(self) -> Outgoing | None: ...

    def set_outgoing(self, out_id: int, status: OutgoingStatus, error: str = "", attempt: bool = False) -> None: ...

    def chat(self, chat_id: str) -> Chat | None: ...

    def project(self, project_id: str) -> Project | None: ...


class DeletionRecords(Protocol):
    """What the delete saga reads and removes."""

    def chats_in_state(self, state: RecordState) -> list[Chat]: ...

    def projects_in_state(self, state: RecordState) -> list[Project]: ...

    def open_task_ids(self, chat_id: str) -> list[str]: ...

    def project_has_chats(self, project_id: str) -> bool: ...

    def purge_chat(self, chat_id: str) -> None: ...

    def purge_project(self, project_id: str) -> None: ...


class StatusRecords(Protocol):
    def queued_count(self) -> int: ...

    def last_seq(self) -> dict[str, int]: ...


class SettingsRecords(Protocol):
    """Saved settings, each a JSON value under a name. Never secrets."""

    def get_setting(self, key: str) -> Any: ...

    def set_setting(self, key: str, value: Any) -> None: ...


class EventLog(Protocol):
    """The stored events of the agents. Accepting an event also applies it to the read model."""

    def ingest(self, events: list[EventEnvelope]) -> tuple[list[tuple[int, EventEnvelope]], int]: ...

    def last_seq(self) -> dict[str, int]: ...

    def prune_events(self, older_than: timedelta) -> int: ...

    def purge_orphans(self) -> int: ...


class DeviceRecords(Protocol):
    """Paired devices. Only a hash of each device token is ever stored."""

    def add(self, device_id: str, name: str, token_hash: str, stamp: str) -> None: ...

    def token_hashes(self) -> list[Record]: ...

    def seen(self, device_id: str, stamp: str) -> None: ...

    def list(self) -> list[Record]: ...

    def revoke(self, device_id: str) -> bool: ...


class TaskLookup(Protocol):
    def task(self, task_id: str) -> Record | None: ...

    def approval(self, approval_id: str) -> Record | None: ...


class ReadQueries(Protocol):
    """Every question the HTTP layer asks about stored data. Read-only, except marking a notification read."""

    def projects(self) -> list[Project]: ...

    def chats(self, project_id: str) -> list[Record]: ...

    def chat_titles(self) -> dict[str, str]: ...

    def pending_outgoing(self, chat_id: str) -> list[Outgoing]: ...

    def queued_count(self) -> int: ...

    def stream_position(self) -> int: ...

    def events_after(self, pos: int, limit: int, chat_id: str | None = None) -> list[Record]: ...

    def task_events(self, task_id: str, limit: int = 2000) -> tuple[list[Record], int]: ...

    def llm_calls(self, since: timedelta, limit: int = 2000) -> list[Record]: ...

    def messages(self, chat_id: str, before: int | None, limit: int) -> list[Record]: ...

    def search_messages(self, text: str, limit: int) -> list[Record]: ...

    def task(self, task_id: str) -> Record | None: ...

    def chat_tasks(self, chat_id: str) -> list[Record]: ...

    def find_tasks(self, state: str, text: str | None, limit: int) -> list[Record]: ...

    def pending_approvals(self, chat_id: str | None = None) -> list[Record]: ...

    def pending_approval_count(self) -> int: ...

    def notifications(self, unread: bool, limit: int) -> list[Record]: ...

    def mark_notification_read(self, notification_id: int) -> None: ...


class MetricsHistory(Protocol):
    def add(self, sample: MetricsSample) -> None: ...

    def latest(self) -> Record | None: ...

    def history(self, span: timedelta, max_points: int = 720) -> list[Record]: ...

    def prune(self, keep: timedelta) -> None: ...


# --- the other services --------------------------------------------------------------------------
# Each of these raises `AgentUnavailable` when the service cannot be reached and `AgentRefused` when it says no.


class MainAgent(Protocol):
    async def answer_approval(self, task_id: str, chat_id: str, approval_id: str, decision: str) -> None: ...

    async def cancel(self, task_id: str) -> Record: ...

    async def pause(self, task_id: str) -> Record: ...

    async def resume(self, task_id: str) -> Record: ...

    async def management(self, method: str, path: str, **kwargs: Any) -> Reply: ...

    async def ready(self) -> Record | None: ...


class VoiceAgent(Protocol):
    def turn(self, chat_id: str, body: Record) -> AsyncIterator[Record]: ...

    async def direct(self, chat_id: str, body: Record) -> Record: ...

    async def request(self, method: str, path: str, **kwargs: Any) -> Reply: ...

    async def hear(self, wav: bytes) -> Record | None: ...

    async def delete_chat(self, chat_id: str) -> None: ...

    async def ready(self) -> Record | None: ...


class RetentionTarget(Protocol):
    """A service that keeps working data and takes the period from the gateway."""

    async def set_retention(self, days: int) -> None: ...


class SpeechService(Protocol):
    async def call(self, method: str, path: str, **kwargs: Any) -> Reply: ...


class PublicAddress(Protocol):
    """This PC's address as paired devices reach it, when one is known."""

    async def url(self) -> str | None: ...


class BackupParticipants(Protocol):
    """The services that copy their own data when the gateway asks."""

    def names(self) -> list[str]: ...

    async def copy(self, name: str, target_dir: str) -> Record: ...
